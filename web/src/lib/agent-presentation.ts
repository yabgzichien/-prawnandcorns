import type { AgentCard } from "./agent";

/** The structured card is authoritative. Don't repeat the model's long, sometimes
 * inconsistently formatted schedule in a second prose copy above it. */
export function presentGeminiAnswer(
  modelText: string,
  cards: AgentCard[],
  model: string,
  fallbackFrom?: string,
): string {
  const fallback = fallbackFrom
    ? `**Model fallback:** ${fallbackFrom} is currently unavailable. This answer was generated by ${model}.\n\n`
    : "";
  const studyCard = cards.find((card): card is Extract<AgentCard, { kind: "study-plan" }> => card.kind === "study-plan");
  if (!studyCard) return fallback + modelText;
  const count = studyCard.proposal.sessions.length;
  if (!count) return fallback + "I couldn't propose study sessions yet. Review the assumptions below, then try again with more details. Nothing has been saved.";
  return fallback + `I found ${count} possible study session${count === 1 ? "" : "s"} using fictional coursework. Review the schedule, meeting assumptions and other tasks below. You can edit or remove sessions before confirming. Nothing has been saved.`;
}

export type AgentTextBlock =
  | { kind: "paragraph"; text: string }
  | { kind: "heading"; text: string }
  | { kind: "list"; items: string[] };

/** Small, safe Markdown subset for Gemini responses. No HTML evaluation. */
export function parseAgentText(text: string): AgentTextBlock[] {
  const lines = text.replace(/\r\n?/g, "\n").split("\n");
  const blocks: AgentTextBlock[] = [];
  const listItem = /^\s*(?:[-*]|\d+[.)])\s+(.+)$/;
  const heading = /^#{1,3}\s+(.+)$/;
  let index = 0;
  while (index < lines.length) {
    const line = lines[index].trim();
    if (!line) { index++; continue; }
    const head = line.match(heading);
    if (head) { blocks.push({ kind: "heading", text: head[1] }); index++; continue; }
    if (listItem.test(line)) {
      const items: string[] = [];
      while (index < lines.length) {
        const match = lines[index].match(listItem);
        if (!match) break;
        items.push(match[1]);
        index++;
      }
      blocks.push({ kind: "list", items });
      continue;
    }
    const parts: string[] = [];
    while (index < lines.length && lines[index].trim() && !listItem.test(lines[index]) && !heading.test(lines[index].trim())) {
      parts.push(lines[index].trim());
      index++;
    }
    blocks.push({ kind: "paragraph", text: parts.join("\n") });
  }
  return blocks;
}
